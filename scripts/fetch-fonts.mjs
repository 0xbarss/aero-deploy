#!/usr/bin/env node
/**
 * Downloads the latin subset of each webfont and writes a self-hosted @font-face sheet.
 *
 * The dashboard is served to phones on a LAN that may have no route to the internet, so the
 * fonts travel with the server instead of being fetched from a font CDN at runtime. Only the
 * latin subset is kept, which is what the interface uses.
 *
 * Google serves each family as a variable font, so one file covers the whole weight range and
 * the @font-face rules declare that range.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const FONT_DIR = join(import.meta.dirname, "..", "public", "fonts");
const CSS_FILE = join(FONT_DIR, "fonts.css");

const UA =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

/** The weight axis each family ships with. */
const FAMILIES = [
  { family: "Space Grotesk", slug: "space-grotesk", range: "300 700" },
  { family: "Inter", slug: "inter", range: "100 900" },
  { family: "JetBrains Mono", slug: "jetbrains-mono", range: "100 800" },
];

/** The latin block of a Google Fonts stylesheet, as the URL of its woff2 file. */
function latinUrl(css, family) {
  const blocks = css.split("@font-face");
  for (const block of blocks) {
    if (!block.includes(`font-family: '${family}'`)) continue;
    if (!block.includes("unicode-range: U+0000-00FF")) continue;
    const match = block.match(/url\((https:\/\/[^)]+\.woff2)\)/);
    if (match) return match[1];
  }
  throw new Error(`No latin subset found for ${family}`);
}

async function download(url) {
  const response = await fetch(url, { headers: { "User-Agent": UA } });
  if (!response.ok) throw new Error(`GET ${url} answered ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

await mkdir(FONT_DIR, { recursive: true });

const rules = [];
for (const { family, slug, range } of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family)}:wght@${range.replace(" ", ";")}&display=swap`;
  const css = await (await fetch(url, { headers: { "User-Agent": UA } })).text();
  const file = `${slug}.woff2`;
  await writeFile(join(FONT_DIR, file), await download(latinUrl(css, family)));
  rules.push(
    [
      "@font-face {",
      `  font-family: "${family}";`,
      "  font-style: normal;",
      `  font-weight: ${range};`,
      "  font-display: swap;",
      `  src: url("/fonts/${file}") format("woff2");`,
      "}",
    ].join("\n"),
  );
  console.log(`${family} (${range}) -> ${file}`);
}

await writeFile(
  CSS_FILE,
  `${[
    "/* Generated by scripts/fetch-fonts.mjs. Self-hosted so the dashboard works on an offline LAN. */",
    ...rules,
  ].join("\n\n")}\n`,
);
console.log(`Wrote ${CSS_FILE}`);
